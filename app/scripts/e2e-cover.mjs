import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';
import { writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import assert from 'node:assert/strict';
const file=join(process.cwd(),'data','cover-test-'+Date.now()+'.json');
const fixture={id:'cover-test',name:'Image test',theme:'mix',description:'Test image',songIds:[]};
writeFileSync(file,JSON.stringify([fixture]));
const server=spawn(process.execPath,['server.js'],{env:{...process.env,PORT:'3212',LISTS_FILE:file},stdio:['ignore','pipe','pipe']});
let browser;
try{
 await new Promise((resolve,reject)=>{server.stdout.on('data',resolve);server.once('exit',code=>reject(Error('Server '+code)));setTimeout(()=>reject(Error('Server timeout')),10000).unref()});
 browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3212/host.html');await page.click('#manage');
 const png=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=800;c.height=400;const x=c.getContext('2d');x.fillStyle='#e64980';x.fillRect(0,0,800,400);return c.toDataURL('image/png').split(',')[1]});
 await page.setInputFiles('#list-cover',{name:'fond.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
 await page.waitForFunction(()=>document.getElementById('cover-status').textContent.includes('Image prête'));
 assert.match(await page.getAttribute('#cover-preview','src'),/^data:image\/jpeg/);
 await page.click('#save-list');await page.waitForFunction(()=>document.getElementById('save-status').textContent.includes('Liste enregistrée'));
 await page.reload();await page.waitForSelector('.style-card');
 assert.match(await page.getAttribute('.style-card img','src'),/^data:image\/jpeg/);
 assert.match(await page.getAttribute('.hero-art','src'),/^data:image\/jpeg/);
 await page.click('#explore-universe');assert.match(await page.getAttribute('#detail-cover img','src'),/^data:image\/jpeg/);
 await page.click('#edit-list');
 const previous = await page.getAttribute('#cover-preview','src');
 const replacement = await page.evaluate(()=>{const c=document.createElement('canvas');c.width=800;c.height=400;const x=c.getContext('2d');x.fillStyle='#247ba0';x.fillRect(0,0,800,400);return c.toDataURL('image/png').split(',')[1]});
 await page.setInputFiles('#list-cover',{name:'nouveau-fond.png',mimeType:'image/png',buffer:Buffer.from(replacement,'base64')});
 await page.waitForFunction(()=>document.getElementById('cover-status').textContent.includes('Image prête'));
 const nextCover = await page.getAttribute('#cover-preview','src'); assert.notEqual(nextCover,previous);
 await page.click('#save-list'); await page.waitForFunction(()=>document.getElementById('save-status').textContent.includes('Liste enregistrée'));
 assert.equal(await page.getAttribute('#cover-preview','src'),nextCover);
 await page.reload();await page.waitForSelector('.style-card');assert.equal(await page.getAttribute('.style-card img','src'),nextCover);
 await page.click('#explore-universe');await page.click('#edit-list');
 await page.screenshot({path:'e2e-shots/playlist-image-editor.png',fullPage:true});
 await page.click('#remove-cover');await page.click('#save-list');await page.waitForFunction(()=>document.getElementById('save-status').textContent.includes('Liste enregistrée'));
 await page.reload();await page.waitForSelector('.style-card');assert.match(await page.getAttribute('.style-card img','src'),/universe-mix.svg$/);
 assert.deepEqual(errors,[]);
 console.log('OK import PNG, optimisation JPEG, aperçu, sauvegarde, rechargement, carte/hero/détail, retour illustration, aucune erreur JS');
}finally{await browser?.close();server.kill();await new Promise(r=>server.once('exit',r));rmSync(file,{force:true})}
